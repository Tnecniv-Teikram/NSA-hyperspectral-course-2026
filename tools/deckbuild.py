"""
deckbuild.py — the shared look and feel for the course slide decks.

Every deck in ``slides/`` is generated by a small script in ``tools/decks/`` that uses this
module, so all decks share one layout, palette and footer. To restyle the whole course
(e.g. to the Space42 template), change the palette below — or open the generated .pptx in
PowerPoint and apply your own theme, since these are ordinary PowerPoint files.

    from deckbuild import Deck
    d = Deck("Preprocessing", "Week 1 · Session 5", notebook="11_preprocessing.ipynb")
    d.objectives(["Apply QA masks", "Remove bad bands"])
    d.bullets("Why mask first", ["Clouds bias every statistic", "..."], notes="Say this out loud")
    d.figure("SNR per band", "11_preprocessing/03_snr.png", caption="Tanager SNR")
    d.handover("11_preprocessing.ipynb", ["Run sections 1–4", "Stop at the exercises"])
    d.save()

Slide hygiene is enforced: too many bullets, or bullets that are too long, raise an error
rather than silently overflowing the slide.
"""
from pathlib import Path

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.text import MSO_ANCHOR, PP_ALIGN
from pptx.util import Emu, Inches, Pt

ROOT = Path(__file__).resolve().parents[1]
FIG_DIR = ROOT / "slides" / "figures"
OUT_DIR = ROOT / "slides"

# --- palette (swap these for your own brand) ------------------------------------------
NAVY = RGBColor(0x0A, 0x23, 0x42)
TEAL = RGBColor(0x2C, 0xA6, 0xA4)
SAND = RGBColor(0xE8, 0xC4, 0x6A)
INK = RGBColor(0x1A, 0x1A, 0x1A)
MUTED = RGBColor(0x5A, 0x6B, 0x7B)
PAPER = RGBColor(0xFF, 0xFF, 0xFF)
LIGHT = RGBColor(0xF2, 0xF5, 0xF8)

W, H = Inches(13.333), Inches(7.5)
MARGIN = Inches(0.62)
TITLE_H = Inches(1.0)
BODY_TOP = Inches(1.65)
BODY_H = H - BODY_TOP - Inches(0.75)

MAX_BULLETS = 9
MAX_BULLET_CHARS = 190


def _rich(text):
    """Split text into (segment, bold, italic) runs for **bold** and *italic* markup."""
    import re as _re
    out, pos = [], 0
    for m in _re.finditer(r"\*\*(.+?)\*\*|\*(.+?)\*", text):
        if m.start() > pos:
            out.append((text[pos:m.start()], False, False))
        out.append((m.group(1), True, False) if m.group(1) is not None else (m.group(2), False, True))
        pos = m.end()
    if pos < len(text):
        out.append((text[pos:], False, False))
    return out or [(text, False, False)]


class Deck:
    def __init__(self, title, session, notebook=None, subtitle=None, week=None):
        self.title, self.session, self.notebook = title, session, notebook
        self.subtitle, self.week = subtitle, week
        self.prs = Presentation()
        self.prs.slide_width, self.prs.slide_height = W, H
        self._blank = self.prs.slide_layouts[6]
        self._title_slide()

    # ---------------------------------------------------------------- internals
    def _slide(self, bg=PAPER):
        s = self.prs.slides.add_slide(self._blank)
        self._rect(s, 0, 0, W, H, bg, line=None)
        return s

    @staticmethod
    def _rect(slide, x, y, w, h, fill, line=None):
        from pptx.enum.shapes import MSO_SHAPE
        shp = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, int(x), int(y), int(w), int(h))
        shp.fill.solid()
        shp.fill.fore_color.rgb = fill
        if line is None:
            shp.line.fill.background()
        else:
            shp.line.color.rgb = line
        shp.shadow.inherit = False
        return shp

    @staticmethod
    def _text(slide, x, y, w, h, text, size=18, color=INK, bold=False, align=PP_ALIGN.LEFT,
              font="Calibri", anchor=MSO_ANCHOR.TOP, spacing=1.0, italic=False):
        box = slide.shapes.add_textbox(int(x), int(y), int(w), int(h))
        tf = box.text_frame
        tf.word_wrap = True
        tf.vertical_anchor = anchor
        for i, line in enumerate(str(text).split("\n")):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.alignment = align
            p.line_spacing = spacing
            run = p.add_run()
            run.text = line
            run.font.size = Pt(size)
            run.font.bold = bold
            run.font.italic = italic
            run.font.color.rgb = color
            run.font.name = font
        return box

    def _header(self, slide, title, kicker=None):
        self._rect(slide, 0, 0, W, Inches(0.09), TEAL)
        if kicker:
            self._text(slide, MARGIN, Inches(0.34), W - 2 * MARGIN, Inches(0.3), kicker.upper(),
                       size=11, color=TEAL, bold=True)
        self._text(slide, MARGIN, Inches(0.62), W - 2 * MARGIN, TITLE_H, title,
                   size=30 if len(str(title)) < 60 else 25, color=NAVY, bold=True)

    def _footer(self, slide):
        n = len(self.prs.slides._sldIdLst)
        self._text(slide, MARGIN, H - Inches(0.52), W - 2 * MARGIN - Inches(0.6), Inches(0.3),
                   f"Space Academy 2026 · Hyperspectral course · {self.session}", size=9, color=MUTED)
        self._text(slide, W - MARGIN - Inches(0.6), H - Inches(0.52), Inches(0.6), Inches(0.3),
                   str(n), size=9, color=MUTED, align=PP_ALIGN.RIGHT)

    @staticmethod
    def _notes(slide, text):
        if text:
            slide.notes_slide.notes_text_frame.text = text

    def _bullet_frame(self, slide, items, x, y, w, h, size=None):
        if len(items) > MAX_BULLETS:
            raise ValueError(f"{len(items)} bullets on one slide (max {MAX_BULLETS}): {items[0][:40]!r}")
        for it in items:
            t = it[0] if isinstance(it, (tuple, list)) else it
            if len(str(t)) > MAX_BULLET_CHARS:
                raise ValueError(f"bullet too long ({len(str(t))} chars): {str(t)[:60]!r}")
        if size is None:
            size = 21 if len(items) <= 5 else (19 if len(items) <= 7 else 17)
        box = slide.shapes.add_textbox(int(x), int(y), int(w), int(h))
        tf = box.text_frame
        tf.word_wrap = True
        tf.vertical_anchor = MSO_ANCHOR.MIDDLE if len(items) <= 6 else MSO_ANCHOR.TOP
        first = True
        for it in items:
            text, level = (it if isinstance(it, (tuple, list)) else (it, 0))
            p = tf.paragraphs[0] if first else tf.add_paragraph()
            first = False
            p.level = level
            p.space_after = Pt(10 if level == 0 else 5)
            p.line_spacing = 1.15
            dot = p.add_run()
            dot.text = ("▪  " if level == 0 else "–  ")
            dot.font.size = Pt(size)
            dot.font.color.rgb = TEAL if level == 0 else MUTED
            dot.font.bold = True
            for seg, bold, italic in _rich(str(text)):
                r = p.add_run()
                r.text = seg
                r.font.size = Pt(size - level * 2)
                r.font.bold = bold
                r.font.italic = italic
                r.font.color.rgb = NAVY if bold else (INK if level == 0 else MUTED)
                r.font.name = "Calibri"
        return box

    @staticmethod
    def _fig_path(image):
        p = Path(image)
        return p if p.is_absolute() or p.exists() else FIG_DIR / image

    def _add_image(self, slide, image, x, y, w, h, caption=None):
        from PIL import Image
        path = self._fig_path(image)
        if not path.exists():
            raise FileNotFoundError(f"figure not found: {path}")
        iw, ih = Image.open(path).size
        cap_h = Inches(0.42) if caption else 0
        avail_h = h - cap_h
        scale = min(w / iw, avail_h / ih)
        dw, dh = int(iw * scale), int(ih * scale)
        px, py = int(x + (w - dw) / 2), int(y + (avail_h - dh) / 2)
        slide.shapes.add_picture(str(path), px, py, dw, dh)
        if caption:
            self._text(slide, x, y + avail_h + Emu(20000), w, cap_h, caption, size=12,
                       color=MUTED, align=PP_ALIGN.CENTER, italic=True)

    # ---------------------------------------------------------------- slide types
    def _title_slide(self):
        s = self._slide(NAVY)
        self._rect(s, 0, 0, Inches(0.16), H, TEAL)
        self._text(s, Inches(1.0), Inches(2.1), W - Inches(2.0), Inches(0.4),
                   (self.week or "Space Academy 2026 · Hyperspectral course").upper(), size=13,
                   color=TEAL, bold=True)
        self._text(s, Inches(1.0), Inches(2.6), W - Inches(2.0), Inches(1.6), self.title,
                   size=44, color=PAPER, bold=True)
        if self.subtitle:
            self._text(s, Inches(1.0), Inches(4.3), W - Inches(2.0), Inches(1.0), self.subtitle,
                       size=20, color=RGBColor(0xC9, 0xD6, 0xE0))
        foot = self.session + (f"  ·  practical: {self.notebook}" if self.notebook else "")
        self._text(s, Inches(1.0), H - Inches(1.2), W - Inches(2.0), Inches(0.4), foot,
                   size=13, color=TEAL)

    def section(self, title, subtitle=None):
        s = self._slide(LIGHT)
        self._rect(s, 0, Inches(2.6), W, Inches(1.9), NAVY)
        self._text(s, MARGIN, Inches(2.85), W - 2 * MARGIN, Inches(0.9), title, size=34,
                   color=PAPER, bold=True)
        if subtitle:
            self._text(s, MARGIN, Inches(3.75), W - 2 * MARGIN, Inches(0.6), subtitle, size=17,
                       color=TEAL)
        self._footer(s)
        return s

    def objectives(self, items, title="What you will be able to do", notes=None):
        s = self._slide()
        self._header(s, title, "learning objectives")
        self._bullet_frame(s, items, MARGIN, BODY_TOP, W - 2 * MARGIN, BODY_H)
        self._footer(s)
        self._notes(s, notes)
        return s

    def bullets(self, title, items, kicker=None, notes=None):
        s = self._slide()
        self._header(s, title, kicker)
        self._bullet_frame(s, items, MARGIN, BODY_TOP, W - 2 * MARGIN, BODY_H)
        self._footer(s)
        self._notes(s, notes)
        return s

    def figure(self, title, image, caption=None, kicker=None, notes=None):
        s = self._slide()
        self._header(s, title, kicker)
        self._add_image(s, image, MARGIN, BODY_TOP, W - 2 * MARGIN, BODY_H, caption)
        self._footer(s)
        self._notes(s, notes)
        return s

    def figure_bullets(self, title, image, items, caption=None, kicker=None, notes=None,
                       image_left=False):
        s = self._slide()
        self._header(s, title, kicker)
        half = (W - 2 * MARGIN - Inches(0.4)) / 2
        img_x = MARGIN if image_left else MARGIN + half + Inches(0.4)
        txt_x = MARGIN + half + Inches(0.4) if image_left else MARGIN
        self._add_image(s, image, img_x, BODY_TOP, half, BODY_H, caption)
        self._bullet_frame(s, items, txt_x, BODY_TOP, half, BODY_H,
                           size=18 if len(items) <= 5 else 16)
        self._footer(s)
        self._notes(s, notes)
        return s

    def table(self, title, headers, rows, kicker=None, notes=None, col_widths=None):
        s = self._slide()
        self._header(s, title, kicker)
        nrows, ncols = len(rows) + 1, len(headers)
        h = min(BODY_H, Inches(0.42) * nrows + Inches(0.1))
        shape = s.shapes.add_table(nrows, ncols, int(MARGIN), int(BODY_TOP),
                                   int(W - 2 * MARGIN), int(h))
        tbl = shape.table
        if col_widths:
            total = sum(col_widths)
            for i, cw in enumerate(col_widths):
                tbl.columns[i].width = int((W - 2 * MARGIN) * cw / total)
        for j, head in enumerate(headers):
            cell = tbl.cell(0, j)
            cell.text = str(head)
            cell.fill.solid()
            cell.fill.fore_color.rgb = NAVY
            for p in cell.text_frame.paragraphs:
                for r in p.runs:
                    r.font.size, r.font.bold, r.font.color.rgb = Pt(14), True, PAPER
        size = 14 if len(rows) <= 7 else 12
        for i, row in enumerate(rows, start=1):
            for j, val in enumerate(row):
                cell = tbl.cell(i, j)
                cell.text = str(val)
                cell.fill.solid()
                cell.fill.fore_color.rgb = PAPER if i % 2 else LIGHT
                for p in cell.text_frame.paragraphs:
                    for r in p.runs:
                        r.font.size, r.font.color.rgb = Pt(size), INK
        self._footer(s)
        self._notes(s, notes)
        return s

    def callout(self, statement, detail=None, kicker=None, notes=None):
        s = self._slide(NAVY)
        self._rect(s, 0, 0, Inches(0.16), H, TEAL)
        if kicker:
            self._text(s, Inches(1.0), Inches(1.5), W - Inches(2.0), Inches(0.3), kicker.upper(),
                       size=12, color=TEAL, bold=True)
        self._text(s, Inches(1.0), Inches(2.1), W - Inches(2.0), Inches(2.4), statement, size=32,
                   color=PAPER, bold=True, spacing=1.15)
        if detail:
            self._text(s, Inches(1.0), Inches(4.8), W - Inches(2.0), Inches(1.4), detail, size=17,
                       color=RGBColor(0xC9, 0xD6, 0xE0), spacing=1.2)
        self._notes(s, notes)
        return s

    def code(self, title, code_text, kicker=None, notes=None, caption=None):
        s = self._slide()
        self._header(s, title, kicker)
        lines = code_text.strip("\n").split("\n")
        if len(lines) > 16:
            raise ValueError(f"{len(lines)} code lines on one slide (max 16)")
        box_h = min(BODY_H, Inches(0.32) * len(lines) + Inches(0.5))
        self._rect(s, MARGIN, BODY_TOP, W - 2 * MARGIN, box_h, LIGHT)
        tb = s.shapes.add_textbox(int(MARGIN + Inches(0.2)), int(BODY_TOP + Inches(0.15)),
                                  int(W - 2 * MARGIN - Inches(0.4)), int(box_h - Inches(0.3)))
        tf = tb.text_frame
        tf.word_wrap = True
        for i, line in enumerate(lines):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            r = p.add_run()
            r.text = line
            r.font.size = Pt(15)
            r.font.name = "Consolas"
            r.font.color.rgb = NAVY if line.strip().startswith("#") else INK
        if caption:
            self._text(s, MARGIN, BODY_TOP + box_h + Inches(0.15), W - 2 * MARGIN, Inches(0.6),
                       caption, size=14, color=MUTED)
        self._footer(s)
        self._notes(s, notes)
        return s

    def handover(self, notebook, steps, title="Over to you", minutes=None, notes=None):
        s = self._slide(LIGHT)
        self._header(s, title, "practical")
        self._rect(s, MARGIN, BODY_TOP, W - 2 * MARGIN, Inches(0.85), TEAL)
        label = f"  ▶  {notebook}" + (f"   ·   {minutes} min" if minutes else "")
        self._text(s, MARGIN + Inches(0.2), BODY_TOP + Inches(0.18), W - 2 * MARGIN, Inches(0.6),
                   label, size=22, color=PAPER, bold=True, font="Consolas")
        self._bullet_frame(s, steps, MARGIN, BODY_TOP + Inches(1.2), W - 2 * MARGIN,
                           BODY_H - Inches(1.2))
        self._footer(s)
        self._notes(s, notes)
        return s

    def recap(self, items, title="Recap", notes=None, next_up=None):
        s = self._slide()
        self._header(s, title, "key takeaways")
        self._bullet_frame(s, items, MARGIN, BODY_TOP, W - 2 * MARGIN,
                           BODY_H - (Inches(0.9) if next_up else 0))
        if next_up:
            self._rect(s, MARGIN, H - Inches(1.5), W - 2 * MARGIN, Inches(0.7), LIGHT)
            self._text(s, MARGIN + Inches(0.2), H - Inches(1.38), W - 2 * MARGIN, Inches(0.5),
                       f"Next: {next_up}", size=16, color=NAVY, bold=True)
        self._footer(s)
        self._notes(s, notes)
        return s

    def references(self, items, title="References and further reading", notes=None):
        s = self._slide()
        self._header(s, title)
        box = s.shapes.add_textbox(int(MARGIN), int(BODY_TOP), int(W - 2 * MARGIN), int(BODY_H))
        tf = box.text_frame
        tf.word_wrap = True
        size = 14 if len(items) <= 7 else (12 if len(items) <= 10 else 11)
        for i, ref in enumerate(items):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.space_after = Pt(8 if size == 14 else 5)
            r = p.add_run()
            r.text = ref
            r.font.size = Pt(size)
            r.font.color.rgb = INK
        self._footer(s)
        self._notes(s, notes)
        return s

    # ---------------------------------------------------------------- output
    def save(self, filename=None):
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        name = filename or (self.session.split("·")[-1].strip().lower().replace(" ", "_") + ".pptx")
        path = OUT_DIR / name
        self.prs.save(path)
        print(f"{path.name}: {len(self.prs.slides._sldIdLst)} slides")
        return path
